    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
 // Mengambil data dari form
    String nim = txtNIM.getText().trim();
    String nama = txtNama.getText().trim();
    String prodi = txtProdi.getText().trim();
    String noHp = txtNoHp.getText().trim();
    String email = txtEmail.getText().trim();

    // Mengambil jenis kelamin
    String jenisKelamin = "";

    if (rbLaki.isSelected()) {
        jenisKelamin = "L";
    } else if (rbPerempuan.isSelected()) {
        jenisKelamin = "P";
    }

    // Validasi data
    if (nim.isEmpty() || nama.isEmpty()
            || prodi.isEmpty() || jenisKelamin.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "NIM, Nama, Prodi, dan Jenis Kelamin wajib diisi!",
            "Peringatan",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Menyimpan data ke database
    try {
        model.Peserta peserta = new model.Peserta(
            nim,
            nama,
            jenisKelamin,
            prodi,
            noHp,
            email
        );

        PesertaDao dao = new PesertaDao();

        boolean berhasil = dao.insert(peserta);

        if (berhasil) {

            JOptionPane.showMessageDialog(
                this,
                "Data peserta berhasil disimpan!",
                "Sukses",
                JOptionPane.INFORMATION_MESSAGE
            );

            // Memperbarui tabel setelah data berhasil disimpan
            tampilkanDataPeserta();


        } else {

            JOptionPane.showMessageDialog(
                this,
                "Data peserta gagal disimpan!",
                "Gagal",
                JOptionPane.ERROR_MESSAGE
            );

        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Gagal menyimpan data: " + e.getMessage(),
            "Error Database",
            JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSimpanActionPerformed

